  CHECK (role IN ('master_owner', 'songwriter', 'publisher', 'producer', 'featured_artist', 'performer', 'manager', 'other')),
  CHECK (share_bps BETWEEN 0 AND 10000),
  CHECK (collection_status IN ('unconfirmed', 'registered', 'collecting', 'hold')),
  CHECK (char_length(society_name) <= 120),
