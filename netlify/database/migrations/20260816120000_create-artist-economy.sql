CREATE TABLE IF NOT EXISTS halo_artist_economy_profiles (
  artist_slug TEXT PRIMARY KEY REFERENCES halo_artist_pages(slug) ON DELETE CASCADE,
  owner_member_id TEXT NOT NULL REFERENCES halo_memberships(member_id) ON DELETE CASCADE,
  currency TEXT NOT NULL DEFAULT 'GBP',
  career_stage TEXT NOT NULL DEFAULT 'first_master',
  monthly_income_target_minor BIGINT NOT NULL DEFAULT 0,
  artist_pay_bps INTEGER NOT NULL DEFAULT 5000,
  next_music_bps INTEGER NOT NULL DEFAULT 2000,
  audience_bps INTEGER NOT NULL DEFAULT 1500,
  business_reserve_bps INTEGER NOT NULL DEFAULT 1000,
  experiment_bps INTEGER NOT NULL DEFAULT 500,
  payment_model TEXT NOT NULL DEFAULT 'undecided',
  payment_status TEXT NOT NULL DEFAULT 'not_connected',
  mission_note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (currency ~ '^[A-Z]{3}$'),
  CHECK (career_stage IN ('first_master', 'first_audience', 'repeatable_releases', 'professional_opportunities', 'sustainable_catalogue')),
  CHECK (monthly_income_target_minor BETWEEN 0 AND 100000000000),
  CHECK (artist_pay_bps BETWEEN 0 AND 10000),
  CHECK (next_music_bps BETWEEN 0 AND 10000),
  CHECK (audience_bps BETWEEN 0 AND 10000),
  CHECK (business_reserve_bps BETWEEN 0 AND 10000),
  CHECK (experiment_bps BETWEEN 0 AND 10000),
  CHECK (artist_pay_bps + next_music_bps + audience_bps + business_reserve_bps + experiment_bps = 10000),
  CHECK (payment_model IN ('undecided', 'artist_seller', 'halo_merchant')),
  CHECK (payment_status IN ('not_connected', 'preparing', 'restricted', 'ready')),
  CHECK (char_length(mission_note) <= 2000)
);

CREATE TABLE IF NOT EXISTS halo_artist_rights_works (
  id TEXT PRIMARY KEY,
  artist_slug TEXT NOT NULL REFERENCES halo_artist_pages(slug) ON DELETE CASCADE,
  owner_member_id TEXT NOT NULL REFERENCES halo_memberships(member_id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  work_type TEXT NOT NULL DEFAULT 'recording',
  linked_release_id TEXT REFERENCES halo_release_campaigns(id) ON DELETE SET NULL,
  isrc TEXT NOT NULL DEFAULT '',
  iswc TEXT NOT NULL DEFAULT '',
  upc TEXT NOT NULL DEFAULT '',
  rights_status TEXT NOT NULL DEFAULT 'incomplete',
  one_stop BOOLEAN NOT NULL DEFAULT FALSE,
  master_owner TEXT NOT NULL DEFAULT '',
  publisher_status TEXT NOT NULL DEFAULT 'unknown',
  restrictions TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (id ~ '^[0-9a-f-]{36}$'),
  CHECK (char_length(title) BETWEEN 1 AND 180),
  CHECK (work_type IN ('recording', 'composition')),
  CHECK (char_length(isrc) <= 15),
  CHECK (char_length(iswc) <= 20),
  CHECK (char_length(upc) <= 20),
  CHECK (rights_status IN ('incomplete', 'review', 'cleared', 'hold', 'disputed')),
  CHECK (char_length(master_owner) <= 180),
  CHECK (publisher_status IN ('unknown', 'self_published', 'administered', 'publisher_controlled')),
  CHECK (cardinality(restrictions) <= 20),
  CHECK (char_length(notes) <= 4000)
);

