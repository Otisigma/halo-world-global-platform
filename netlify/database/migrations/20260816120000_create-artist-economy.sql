CREATE TABLE IF NOT EXISTS halo_artist_income_entries (
  id TEXT PRIMARY KEY,
  artist_slug TEXT NOT NULL REFERENCES halo_artist_pages(slug) ON DELETE CASCADE,
  owner_member_id TEXT NOT NULL REFERENCES halo_memberships(member_id) ON DELETE CASCADE,
  work_id TEXT REFERENCES halo_artist_rights_works(id) ON DELETE SET NULL,
  source_type TEXT NOT NULL,
  description TEXT NOT NULL,
  currency TEXT NOT NULL DEFAULT 'GBP',
  gross_minor BIGINT NOT NULL DEFAULT 0,
  fees_minor BIGINT NOT NULL DEFAULT 0,
  tax_reserve_minor BIGINT NOT NULL DEFAULT 0,
  obligations_minor BIGINT NOT NULL DEFAULT 0,
  occurred_on DATE NOT NULL DEFAULT CURRENT_DATE,
  status TEXT NOT NULL DEFAULT 'expected',
  external_reference TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (id ~ '^[0-9a-f-]{36}$'),
  CHECK (source_type IN ('distribution', 'publishing', 'neighbouring_rights', 'direct_sale', 'membership', 'licensing', 'live', 'merchandise', 'service', 'grant', 'other')),
  CHECK (char_length(description) BETWEEN 1 AND 240),
  CHECK (currency ~ '^[A-Z]{3}$'),
  CHECK (gross_minor BETWEEN 0 AND 100000000000),
  CHECK (fees_minor BETWEEN 0 AND gross_minor),
  CHECK (tax_reserve_minor BETWEEN 0 AND gross_minor),
  CHECK (obligations_minor BETWEEN 0 AND gross_minor),
  CHECK (fees_minor + tax_reserve_minor + obligations_minor <= gross_minor),
  CHECK (status IN ('expected', 'received', 'overdue', 'disputed', 'reconciled')),
  CHECK (char_length(external_reference) <= 180),
  CHECK (char_length(notes) <= 4000)
);

